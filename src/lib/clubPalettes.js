/** Case- and punctuation-insensitive search over club names. */
export function searchClubs(query) {
  const needle = query.trim().toLowerCase().replace(/[^a-z0-9]/g, '');

  if (!needle) return CLUB_PALETTES;

  return CLUB_PALETTES.filter(club =>
    club.name.toLowerCase().replace(/[^a-z0-9]/g, '').includes(needle)
  );
}
